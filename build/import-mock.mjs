// Imports the interactive prototype from a Binder mock export into demo/.
//
//   node build/import-mock.mjs [path/to/mock-export]   (default ~/Claude/Binder/3 - Marketing/1 - Mock/v2 - 25102026 Binder-Export-mock)
//
// The prototype is used as-is so the site always shows exactly what was
// approved in the mock. Two things change on the way in:
//   - the 600 KB Lucide bundle is replaced by a subset holding only the icons
//     the prototype names (a few KB), built from that same bundle;
//   - boot.js and embed.css are loaded alongside, so the landing page can embed
//     the prototype in a phone frame and drive it to a given screen.
// Every rewrite must match exactly once; if a new export changes shape, this
// stops with the reason instead of writing a half-working demo.
import { readFileSync, writeFileSync, mkdirSync, copyFileSync } from 'node:fs';
import { join, dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
// The repo lives in Binder/4 - Operations/0.1 - Live product/; mocks in Binder/3 - Marketing/1 - Mock/.
const src = resolve(process.argv[2] || join(root, '..', '..', '..', '3 - Marketing', '1 - Mock', 'v2 - 25102026 Binder-Export-mock'));
const out = join(root, 'demo');
const die = (msg) => { console.error(`import-mock: ${msg}`); process.exit(1); };

let html, lucideSrc;
try {
  html = readFileSync(join(src, 'prototype', 'index.html'), 'utf8');
  lucideSrc = readFileSync(join(src, 'assets', 'lucide.js'), 'utf8');
} catch (e) { die(`cannot read the export at ${src}: ${e.message}`); }

function replaceOnce(text, find, repl, what) {
  const n = text.split(find).length - 1;
  if (n !== 1) die(`expected exactly one ${what}, found ${n} — has the export format changed?`);
  return text.replace(find, repl);
}

// The prototype restores state only when its saved version matches; boot.js
// has to speak the same version or every "go to screen" call is ignored.
const ver = html.match(/saved\.version===(\d+)/);
if (!ver) die('could not find the prototype state version (saved.version===N)');

html = replaceOnce(html, '<script src="../assets/lucide.js"></script>',
  // Absolute paths: vercel.json's cleanUrls serves this page at /demo (no
  // trailing slash), where a relative "boot.js" would resolve to /boot.js.
  `<link rel="stylesheet" href="/demo/embed.css"><script>window.BINDER_STATE_VERSION=${ver[1]}</script><script src="/demo/boot.js"></script><script src="/demo/icons.js"></script>`,
  'Lucide script tag');
html = replaceOnce(html, '<title>Binder</title>', '<title>Binder — interactive demo</title><meta name="robots" content="noindex">', 'title');

// --- Lucide subset --------------------------------------------------------
const require = createRequire(import.meta.url);
const tmp = join(out, '.lucide-full.cjs');
mkdirSync(out, { recursive: true });
writeFileSync(tmp, lucideSrc);
const lucide = require(tmp);
const pascal = (s) => s.replace(/(^|-)([a-z0-9])/g, (_, __, c) => c.toUpperCase());

// Icon names appear as plain string literals (icon('check'), data-lucide="layers",
// icon(vc?'target':'wallet')). Taking every literal that names a real icon is
// deliberately generous: an extra icon costs bytes, a missing one is a blank square.
const literals = new Set([...html.matchAll(/['"]([a-z][a-z0-9-]{0,40})['"]/g)].map((m) => m[1]));
const used = [...literals].filter((n) => lucide.icons[pascal(n)]).sort();
if (used.length < 10) die(`only ${used.length} icons found — the extraction regex no longer matches the prototype`);
const subset = Object.fromEntries(used.map((n) => [pascal(n), lucide.icons[pascal(n)]]));

// The DOM helpers are copied verbatim from the bundle, so icons render exactly
// as they did with the full library.
const start = lucideSrc.indexOf('  const defaultAttributes = {');
const end = lucideSrc.indexOf('  const AArrowDown = [');
if (start < 0 || end < 0 || end < start) die('Lucide bundle layout changed — cannot locate its DOM helpers');
const header = lucideSrc.slice(0, lucideSrc.indexOf('*/') + 2);
const iconsJs = `${header}
// Subset generated by build/import-mock.mjs — ${used.length} of ${Object.keys(lucide.icons).length} icons.
(function () { 'use strict';
${lucideSrc.slice(start, end)}
  const icons = ${JSON.stringify(subset)};
  const createIcons = ({ attrs = {}, nameAttr = 'data-lucide', root = document } = {}) => {
    root.querySelectorAll('[' + nameAttr + ']').forEach((el) => replaceElement(el, { nameAttr, icons, attrs }));
  };
  window.lucide = { createIcons, createElement, icons };
})();
`;

writeFileSync(join(out, 'index.html'), html);
writeFileSync(join(out, 'icons.js'), iconsJs);
copyFileSync(join(src, 'assets', 'LICENSE-lucide'), join(out, 'LICENSE-lucide'));
(await import('node:fs')).rmSync(tmp);

console.log(`import-mock: demo/ from ${src}`);
console.log(`  index.html ${(html.length / 1024).toFixed(0)} KB, state version ${ver[1]}`);
console.log(`  icons.js   ${(iconsJs.length / 1024).toFixed(1)} KB, ${used.length} icons: ${used.join(' ')}`);
